//! Embedded, hash-pinned publisher identity tuples generated by
//! `scripts/build-guide-crosswalk-pack.py` from iptv-org's published API.
//! Tuples only ever name an exact XMLTV header; callers must still find that
//! header in the actual downloaded feed. No names, prefixes or fuzzy rules.
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::{
    collections::{HashMap, HashSet},
    io::Read,
    sync::LazyLock,
};

const PACK: &[u8] = include_bytes!("crosswalk-pack.json.gz");
const PIN: &str = "89715fd9b0fcad115e21212c014683f72fef1b4d551c4366b9205b58bff083fb";
const EXPANDED_LIMIT: u64 = 8 * 1024 * 1024;
const FEED_LIMIT: usize = 256;
const PAIR_LIMIT: usize = 50_000;
const CHANNEL_LIMIT: usize = 100_000;
const RAW_PREFIX: &str = "https://raw.githubusercontent.com/matthuisman/i.mjh.nz/master/";
const SITE_PREFIX: &str = "https://i.mjh.nz/";

pub(crate) struct Pack {
    feeds: HashMap<String, HashMap<String, String>>,
    main_feeds: HashMap<String, String>,
}

/// Projection stamp: changing the pack makes earlier projections recompute.
pub(crate) fn stamp() -> &'static str {
    &PIN[..16]
}

fn text(value: &str, limit: usize) -> bool {
    !value.is_empty() && value.len() <= limit && !value.chars().any(char::is_control)
}

pub(crate) fn parse(bytes: &[u8]) -> Result<Pack, &'static str> {
    if format!("{:x}", Sha256::digest(bytes)) != PIN {
        return Err("guide-pack-hash-mismatch");
    }
    let mut expanded = Vec::new();
    flate2::read::GzDecoder::new(bytes)
        .take(EXPANDED_LIMIT + 1)
        .read_to_end(&mut expanded)
        .map_err(|_| "guide-pack-invalid")?;
    if expanded.len() as u64 > EXPANDED_LIMIT {
        return Err("guide-pack-too-large");
    }
    let root: Value = serde_json::from_slice(&expanded).map_err(|_| "guide-pack-invalid")?;
    if root.get("schemaVersion").and_then(Value::as_u64) != Some(1) {
        return Err("guide-pack-invalid");
    }
    let mut feeds = HashMap::new();
    let mut pairs = 0usize;
    let feed_rows = root
        .get("feeds")
        .and_then(Value::as_object)
        .ok_or("guide-pack-invalid")?;
    if feed_rows.len() > FEED_LIMIT {
        return Err("guide-pack-too-large");
    }
    for (path, rows) in feed_rows {
        if !text(path, 128)
            || !path
                .split('/')
                .all(|p| !p.is_empty() && p.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'))
        {
            return Err("guide-pack-invalid");
        }
        let rows = rows.as_object().ok_or("guide-pack-invalid")?;
        let mut table = HashMap::new();
        for (provider, header) in rows {
            let header = header.as_str().ok_or("guide-pack-invalid")?;
            pairs += 1;
            if pairs > PAIR_LIMIT {
                return Err("guide-pack-too-large");
            }
            if !text(provider, 256) || !provider.contains('@') || !text(header, 512) {
                return Err("guide-pack-invalid");
            }
            table.insert(provider.clone(), header.to_owned());
        }
        feeds.insert(path.clone(), table);
    }
    let mut main_feeds = HashMap::new();
    let main_rows = root
        .get("mainFeeds")
        .and_then(Value::as_object)
        .ok_or("guide-pack-invalid")?;
    for (feed, channels) in main_rows {
        if !text(feed, 64) || feed.contains('@') {
            return Err("guide-pack-invalid");
        }
        for channel in channels.as_array().ok_or("guide-pack-invalid")? {
            let channel = channel.as_str().ok_or("guide-pack-invalid")?;
            if !text(channel, 256) || channel.contains('@') {
                return Err("guide-pack-invalid");
            }
            // One published main feed per channel; a duplicate is a malformed pack.
            if main_feeds
                .insert(channel.to_owned(), feed.clone())
                .is_some()
                || main_feeds.len() > CHANNEL_LIMIT
            {
                return Err("guide-pack-invalid");
            }
        }
    }
    Ok(Pack { feeds, main_feeds })
}

static LOADED: LazyLock<Option<Pack>> = LazyLock::new(|| parse(PACK).ok());

pub(crate) fn loaded() -> Option<&'static Pack> {
    LOADED.as_ref()
}

/// Exact published locations only: no query, fragment, port or credentials.
pub(crate) fn feed_path(location: &str) -> Option<&str> {
    let rest = location
        .strip_prefix(RAW_PREFIX)
        .or_else(|| location.strip_prefix(SITE_PREFIX))?;
    let path = rest
        .strip_suffix(".xml.gz")
        .or_else(|| rest.strip_suffix(".xml"))?;
    (!path.is_empty()
        && path
            .split('/')
            .all(|p| !p.is_empty() && p.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')))
    .then_some(path)
}

impl Pack {
    /// Published main feed of a channel, e.g. `SD` for `Example.us`.
    pub(crate) fn main_feed(&self, channel: &str) -> Option<&str> {
        self.main_feeds.get(channel).map(String::as_str)
    }
    /// `X@F` <-> `X` only when `F` is X's published main feed.
    pub(crate) fn main_feed_alternate(&self, provider: &str) -> Option<String> {
        match provider.split_once('@') {
            Some((channel, feed)) => (!channel.is_empty() && self.main_feed(channel) == Some(feed))
                .then(|| channel.to_owned()),
            None => self
                .main_feed(provider)
                .map(|feed| format!("{provider}@{feed}")),
        }
    }
    /// Exact header for this feed location; a bare ID uses its main feed tuple.
    pub(crate) fn target(&self, location: &str, provider: &str) -> Option<&str> {
        let table = self.feeds.get(feed_path(location)?)?;
        if let Some(header) = table.get(provider) {
            return Some(header);
        }
        if provider.contains('@') {
            return None;
        }
        table
            .get(&format!("{provider}@{}", self.main_feed(provider)?))
            .map(String::as_str)
    }
    /// Additional exact identities to look for in a feed, never including `provider`.
    pub(crate) fn alternates(&self, location: Option<&str>, provider: &str) -> Vec<String> {
        let mut out = Vec::new();
        if let Some(target) = location.and_then(|l| self.target(l, provider)) {
            out.push(target.to_owned());
        }
        if let Some(alternate) = self.main_feed_alternate(provider) {
            out.push(alternate);
        }
        let mut seen = HashSet::new();
        out.retain(|value| value != provider && seen.insert(value.clone()));
        out
    }
}

/// Convenience for callers without a pack handle.
pub(crate) fn alternates(location: Option<&str>, provider: &str) -> Vec<String> {
    loaded().map_or_else(Vec::new, |pack| pack.alternates(location, provider))
}

pub(crate) const SUGGESTION_LIMIT: usize = 16;
#[derive(Debug, serde::Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct FeedSuggestion {
    pub name: String,
    pub location: String,
    /// Saved channels with a published tuple for this feed; not verified coverage.
    pub channels: usize,
}
impl Pack {
    /// Publisher feeds that list at least one of these canonical IDs, most first.
    pub(crate) fn suggestions<'a>(
        &self,
        providers: impl Iterator<Item = &'a str>,
    ) -> Vec<FeedSuggestion> {
        let mut counts: HashMap<&str, usize> = HashMap::new();
        let mut seen = HashSet::new();
        for provider in providers {
            if !seen.insert(provider) {
                continue;
            }
            let qualified = if provider.contains('@') {
                None
            } else {
                self.main_feed(provider).map(|f| format!("{provider}@{f}"))
            };
            for (path, table) in &self.feeds {
                if table.contains_key(provider)
                    || qualified.as_ref().is_some_and(|q| table.contains_key(q))
                {
                    *counts.entry(path.as_str()).or_default() += 1;
                }
            }
        }
        let mut ranked: Vec<_> = counts.into_iter().collect();
        ranked.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
        ranked
            .into_iter()
            .take(SUGGESTION_LIMIT)
            .map(|(path, channels)| FeedSuggestion {
                name: format!("Publisher guide · {path}"),
                location: format!("{RAW_PREFIX}{path}.xml.gz"),
                channels,
            })
            .collect()
    }
}

/// Reads saved, nonremoved channel IDs only; no network and no writes.
pub(crate) fn suggestions_from_catalog(
    c: &rusqlite::Connection,
) -> Result<Vec<FeedSuggestion>, String> {
    let Some(pack) = loaded() else {
        return Ok(Vec::new());
    };
    let ids = catalog_provider_ids(c)?;
    Ok(pack.suggestions(ids.iter().map(String::as_str)))
}
/// Distinct provider IDs of saved, nonremoved channels (at most 100,000).
pub(crate) fn catalog_provider_ids(c: &rusqlite::Connection) -> Result<Vec<String>, String> {
    let mut statement = c
        .prepare("SELECT DISTINCT provider_id FROM channel WHERE provider_id IS NOT NULL AND provider_id<>'' AND NOT EXISTS(SELECT 1 FROM removed r WHERE r.id=channel.id) LIMIT 100001")
        .map_err(|_| "guide-database-operation-failed")?;
    let ids = statement
        .query_map([], |r| r.get::<_, String>(0))
        .map_err(|_| "guide-database-operation-failed")?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|_| "guide-database-operation-failed")?;
    if ids.len() > 100_000 {
        return Err("guide-catalog-channel-limit".into());
    }
    Ok(ids)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_pack_is_pinned_bounded_and_parses() {
        assert_eq!(format!("{:x}", Sha256::digest(PACK)), PIN);
        let pack = loaded().expect("embedded pack");
        assert!(pack.feeds.len() >= 30 && pack.feeds.len() <= FEED_LIMIT);
        assert!(pack.main_feeds.len() > 30_000);
        let mut modified = PACK.to_vec();
        modified[20] ^= 1;
        assert_eq!(parse(&modified).err(), Some("guide-pack-hash-mismatch"));
    }

    #[test]
    fn feed_locations_are_exact_publisher_paths() {
        for (location, path) in [
            (
                "https://raw.githubusercontent.com/matthuisman/i.mjh.nz/master/SamsungTVPlus/us.xml.gz",
                Some("SamsungTVPlus/us"),
            ),
            ("https://i.mjh.nz/Roku/all.xml", Some("Roku/all")),
            ("https://i.mjh.nz/au/Sydney/epg.xml.gz", Some("au/Sydney/epg")),
            ("https://i.mjh.nz/Roku/all.xml.gz?x=1", None),
            ("https://i.mjh.nz/Roku/../all.xml", None),
            ("https://i.mjh.nz:443/Roku/all.xml", None),
            ("http://i.mjh.nz/Roku/all.xml", None),
            ("https://evil.invalid/Roku/all.xml", None),
            ("https://i.mjh.nz/Roku/all.m3u8", None),
        ] {
            assert_eq!(feed_path(location), path, "{location}");
        }
    }

    #[test]
    fn exact_targets_require_the_feed_and_use_only_published_main_feeds() {
        let pack = loaded().unwrap();
        let samsung = "https://i.mjh.nz/SamsungTVPlus/us.xml.gz";
        // Recorded in the 2026-10-16 identity research as an exact Samsung US tuple.
        assert_eq!(
            pack.target(samsung, "beINSPORTSXTRA.us@SD"),
            Some("USAJ4300001Q7")
        );
        // Tuples are scoped per feed. Roku's registry row for this channel names a
        // header absent from the live Roku feed, so the verified pack omits it.
        assert_eq!(
            pack.target("https://i.mjh.nz/Roku/all.xml.gz", "beINSPORTSXTRA.us@SD"),
            None
        );
        assert_eq!(
            pack.target("https://i.mjh.nz/PlutoTV/us.xml.gz", "beINSPORTSXTRA.us@SD"),
            None
        );
        assert_eq!(pack.target(samsung, "NotAChannel.us@SD"), None);
        // Bare playlist IDs reach the main-feed tuple, but never another feed's.
        if pack.main_feed("beINSPORTSXTRA.us") == Some("SD") {
            assert_eq!(
                pack.target(samsung, "beINSPORTSXTRA.us"),
                Some("USAJ4300001Q7")
            );
        }
        assert_eq!(pack.target(samsung, "beINSPORTSXTRA.us@HD"), None);
    }

    #[test]
    fn main_feed_alternates_are_bidirectional_and_conservative() {
        let pack = loaded().unwrap();
        let (channel, feed) = pack
            .main_feeds
            .iter()
            .find(|(_, f)| f.as_str() == "SD")
            .map(|(c, f)| (c.clone(), f.clone()))
            .unwrap();
        assert_eq!(
            pack.main_feed_alternate(&format!("{channel}@{feed}")),
            Some(channel.clone())
        );
        assert_eq!(
            pack.main_feed_alternate(&channel),
            Some(format!("{channel}@SD"))
        );
        assert_eq!(
            pack.main_feed_alternate(&format!("{channel}@NotMain")),
            None
        );
        assert_eq!(pack.main_feed_alternate("Unknown.zz"), None);
        assert_eq!(pack.main_feed_alternate("@SD"), None);
        assert!(!pack.alternates(None, &channel).contains(&channel));
    }

    #[test]
    fn suggestions_rank_publisher_feeds_by_saved_canonical_ids_and_are_bounded() {
        let pack = loaded().unwrap();
        let ids = [
            "beINSPORTSXTRA.us@SD",
            "beINSPORTSXTRA.us",
            "Pac12Insider.us@SD",
            "Unknown.zz",
        ];
        let result = pack.suggestions(ids.iter().copied());
        let samsung = result
            .iter()
            .find(|s| s.location.ends_with("/SamsungTVPlus/us.xml.gz"))
            .expect("Samsung US suggested");
        assert_eq!(
            samsung.location,
            format!("{RAW_PREFIX}SamsungTVPlus/us.xml.gz")
        );
        assert!(samsung.channels >= 2);
        assert!(result.windows(2).all(|w| w[0].channels >= w[1].channels));
        assert!(result.iter().all(|s| feed_path(&s.location).is_some()));
        assert!(pack.suggestions(std::iter::empty()).is_empty());
        let every: Vec<String> = pack
            .feeds
            .values()
            .flat_map(|t| t.keys().cloned())
            .collect();
        assert!(pack.suggestions(every.iter().map(String::as_str)).len() <= SUGGESTION_LIMIT);
    }

    #[test]
    fn catalog_suggestions_read_only_nonremoved_saved_ids() {
        let c = rusqlite::Connection::open_in_memory().unwrap();
        c.execute_batch(
            "CREATE TABLE channel(id TEXT PRIMARY KEY,source_id TEXT,provider_id TEXT);
             CREATE TABLE removed(id TEXT PRIMARY KEY);
             INSERT INTO channel VALUES('a','s','beINSPORTSXTRA.us@SD'),('b','s','Pac12Insider.us@SD'),('c','s',NULL);
             INSERT INTO removed VALUES('b');",
        )
        .unwrap();
        let result = suggestions_from_catalog(&c).unwrap();
        let samsung = result
            .iter()
            .find(|s| s.location.ends_with("/SamsungTVPlus/us.xml.gz"))
            .unwrap();
        assert_eq!(samsung.channels, 1);
    }

    #[test]
    fn conflicting_publisher_rows_never_reach_the_pack() {
        let pack = loaded().unwrap();
        let expanded = {
            let mut out = Vec::new();
            flate2::read::GzDecoder::new(PACK)
                .read_to_end(&mut out)
                .unwrap();
            serde_json::from_slice::<Value>(&out).unwrap()
        };
        let quarantined = expanded["quarantined"].as_object().unwrap();
        assert!(!quarantined.is_empty());
        for (path, ids) in quarantined {
            for id in ids.as_array().unwrap() {
                let location = format!("https://i.mjh.nz/{path}.xml");
                assert_eq!(pack.target(&location, id.as_str().unwrap()), None);
            }
        }
    }
}
